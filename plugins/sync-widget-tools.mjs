// Copies plugins/protocol/widget-tools.json (single source of the widget-tool schemas) into each plugin:
// installing a plugin only carries its own folder. The apps guide (protocol/apps-guide.md) is embedded as `appGuide`
// (returned by the `agentui_app_guide` tool) and also published as the `agentui-apps` skill for Claude Code-style runtimes.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
const here = new URL('.', import.meta.url);
const spec = JSON.parse(readFileSync(new URL('protocol/widget-tools.json', here), 'utf8'));
const guide = readFileSync(new URL('protocol/apps-guide.md', here), 'utf8');
const out = JSON.stringify({ ...spec, appGuide: guide }, null, 2) + '\n';
for (const dest of ['hermes-agentui/widget_tools.json', 'openclaw-agentui/src/widget-tools.json']) writeFileSync(new URL(dest, here), out);

const skillDir = new URL('../.claude/skills/agentui-apps/', here);
mkdirSync(skillDir, { recursive: true });
writeFileSync(
  new URL('SKILL.md', skillDir),
  `---\nname: agentui-apps\ndescription: Build an app (React frontend + backend API) that appears in the Apps tab of AgentUI and follows its UI. Use when the user asks an AgentUI agent to create a tool, tracker, dashboard or mini-application, or to modify an existing app.\n---\n\n<!-- Generated by plugins/sync-widget-tools.mjs from plugins/protocol/apps-guide.md — edit the source. -->\n\n${guide}`,
);
