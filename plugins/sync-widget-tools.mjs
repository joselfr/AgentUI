// Copies plugins/protocol/widget-tools.json (single source of the widget-tool schemas) into each plugin:
// installing a plugin only carries its own folder. The miniapps guide (protocol/miniapps-guide.md) is embedded as `miniappGuide`
// (returned by the `agentui_miniapp_guide` tool) and also published as the `agentui-miniapps` skill for Claude Code-style runtimes.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
const here = new URL('.', import.meta.url);
const spec = JSON.parse(readFileSync(new URL('protocol/widget-tools.json', here), 'utf8'));
const guide = readFileSync(new URL('protocol/miniapps-guide.md', here), 'utf8');
const out = JSON.stringify({ ...spec, miniappGuide: guide }, null, 2) + '\n';
for (const dest of ['hermes-agentui/widget_tools.json', 'openclaw-agentui/src/widget-tools.json']) writeFileSync(new URL(dest, here), out);

const skillDir = new URL('../.claude/skills/agentui-miniapps/', here);
mkdirSync(skillDir, { recursive: true });
writeFileSync(
  new URL('SKILL.md', skillDir),
  `---\nname: agentui-miniapps\ndescription: Build a miniapp (React front + handlers) that appears in the Miniapps tab of AgentUI and follows its UI. Use when the user asks an AgentUI agent to create a tool, tracker, dashboard or small application, or to modify an existing miniapp.\n---\n\n<!-- Generated by plugins/sync-widget-tools.mjs from plugins/protocol/miniapps-guide.md — edit the source. -->\n\n${guide}`,
);
